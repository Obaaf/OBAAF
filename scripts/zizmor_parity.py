# OBAAF's findings, and the comparison


@dataclass(frozen=True)
class Hit:
    rule: str
    job: str | None
    state: str
    step: tuple | None = None      # the step the finding names, as (line, name); None for one on the job
    covers: frozenset = frozenset()   # for OBAAF-GHA-006's `restores` finding: every step it is about


@dataclass
class FileResult:
    hits: list
    errors: list
    steps: dict    # job id -> {(N,) or (N, M): the (line, name) of OBAAF's step(s) at that place}


def _step_places(job) -> dict:
    """Each place in a job's written `steps` ((N,), and (N, M) inside a `parallel` group) and the OBAAF
    steps there, matched by the YAML node itself, so steps on one line or inside groups stay apart."""
    raw = job.raw.get("steps") if isinstance(job.raw, dict) else None
    places: dict = {}
    if not isinstance(raw, list):
        return places
    for n, item in enumerate(raw):
        inner = item.get("parallel") if isinstance(item, dict) and "parallel" in item else None
        targets = [((n, m), sub) for m, sub in enumerate(inner)] if isinstance(inner, list) else [((n,), item)]
        for place, node in targets:
            places[place] = {(st.line, st.name) for st in job.steps if st.raw is node}
    return places


def obaaf_findings(path: Path) -> FileResult:
    """What `obaaf check FILE` (no configuration, GitHub Actions) finds on one workflow file, and which of
    OBAAF's steps is at each place of each job's `steps`."""
    from obaaf import checker
    from obaaf.checker import workflow as wf_mod
    from obaaf.checker.rules import WorkflowRules

    config = checker.Config.load(path.parent, None)
    result = checker.check(path, config=config, platform="github")
    errors = list(result.errors)
    parsed = wf_mod.parse(path.name, path.read_text(encoding="utf-8"))
    if parsed.error and not errors:
        errors.append(parsed.error)
    steps = {job_id: _step_places(job) for job_id, job in parsed.jobs.items()}
    hits = []
    for f in result.findings:
        covers = frozenset()
        job = parsed.jobs.get(f.job) if f.job is not None else None
        if f.rule == "OBAAF-GHA-006" and f.kind.startswith("restores") and job is not None:
            # One finding for all the job's cache steps, at the first; the others are in its facts. The
            # steps are the ones the rule counts (WorkflowRules._restores_cache), not a match of the facts.
            covers = frozenset((st.line, st.name) for st in job.steps if WorkflowRules._restores_cache(st))
        hits.append(Hit(f.rule, f.job, f.state, (f.line, f.step) if f.step is not None else None, covers))
    return FileResult(hits, errors, steps)


@dataclass
class Outcome:
    case: Case
    status: str        # answered, silent (recorded), unexplained
    hits: list = field(default_factory=list)
    reason: str = ""
    unmet: list = field(default_factory=list)   # what zizmor named that no OBAAF finding answers


@dataclass
class Comparison:
    set: str
    outcomes: list
    stale: list        # silent entries that name no case, or a case OBAAF answers: (entry, why)
    recorded: list     # (Recorded, ok: bool, hits)
    errors: dict       # file -> what OBAAF could not read in it

    @property
    def failures(self) -> int:
        return (sum(o.status == "unexplained" for o in self.outcomes) + len(self.stale)
                + sum(not ok for _, ok, _ in self.recorded) + len(self.errors))


def _place(place: tuple) -> str:
    return f"step {place[0] + 1}" + (f", parallel step {place[1] + 1}" if len(place) > 1 else "")


def answer(case: Case, rules: list, result: FileResult) -> tuple[list, list, set]:
    """OBAAF's findings on a case's job, and what in the case none of them answers. A finding counts when
    it is of a mapped rule and not `fixed`, and is on the case's job (anywhere, for a case on the file).
    The job itself, when zizmor named it or a part of it that is not a step, is answered by any such
    finding. Each step zizmor named is answered only by a finding on that step, or by OBAAF-GHA-006's
    `restores` finding when it is about that step: a finding on the job as a whole answers no step."""
    found = [h for h in result.hits if h.rule in rules and h.state != "fixed"
             and (case.job is None or h.job == case.job)]
    if case.job is None:
        return found, ([] if found else ["the file"]), (set() if found else {"file"})
    unmet: list = []
    missing: set = set()   # the places none answers, and "job" for the job
    if case.job_level and not found:
        unmet.append(f"job {case.job}")
        missing.add("job")
    places = result.steps.get(case.job)
    if case.steps and places is None:
        raise ParityError(f"{case.file}: OBAAF's reader has no job {case.job!r}, which zizmor names")
    for place in case.steps:
        keys = places.get(tuple(place))
        if not keys:
            raise ParityError(f"{case.file}: job {case.job!r} has no {_place(place)} OBAAF reads, which zizmor names")
        if not any(h.step in keys or keys & h.covers for h in found):
            line = min(k[0] for k in keys)
            unmet.append(f"{_place(place)} (line {line})")
            missing.add(tuple(place))
    return found, unmet, missing


def compare(mapping: Mapping, set_name: str, cases: list[Case], base: Path, findings=obaaf_findings) -> Comparison:
    fileset = mapping.sets[set_name]
    files = set(fileset.files(base))
    by_file: dict = {}
    errors: dict = {}

    def result_of(rel: str) -> FileResult:
        if rel not in by_file:
            if rel not in files:
                raise ParityError(f"set {set_name}: {rel} is not among the set's files")
            result = findings(base / rel)
            by_file[rel] = result
            if result.errors:
                errors[rel] = result.errors
        return by_file[rel]

    silent = {(s.file, s.job, s.audit): s for s in mapping.silent if s.set == set_name}
    for key, entry in silent.items():
        if entry.file not in files:
            raise ParityError(f"set {set_name}: a silent entry names {entry.file}, which is not among its files")
    used: set = set()
    outcomes = []
    partly: set = set()
    listed: set = set()
    for case in cases:
        if case.audit not in mapping.audits:
            continue
        result = result_of(case.file)
        entry = silent.get(case.key())
        if result.errors:
            # OBAAF could not read the file: no reason recorded about it can be checked (a failure of its own).
            found, unmet, missing = [], ["a file OBAAF could not read"], {"file"}
        else:
            found, unmet, missing = answer(case, mapping.audits[case.audit], result)
        if not unmet:
            outcomes.append(Outcome(case, "answered", found))
        elif entry is not None:
            used.add(case.key())
            if found and set(entry.steps) != missing:
                partly.add(case.key())
            elif not found and entry.steps:
                listed.add(case.key())
            label = f"{entry.kind}: " if entry.kind == "narrower" else f"gap ({entry.issue}): "
            outcomes.append(Outcome(case, "silent", found, label + entry.reason, unmet))
        else:
            outcomes.append(Outcome(case, "unexplained", found, unmet=unmet))
    answered = {o.case.key() for o in outcomes if o.status == "answered"}
    stale = []
    for key, entry in silent.items():
        if key in answered:
            stale.append((entry, "OBAAF now answers this case; remove the entry"))
        elif key in partly:
            stale.append((entry, "OBAAF reports a mapped rule on this job, though not on all zizmor names, and the "
                                 "entry's `steps` are not the places it leaves unanswered; judge the reason again"))
        elif key in listed:
            stale.append((entry, "the entry names steps, but OBAAF reports none of the audit's rules on this job; "
                                 "remove its `steps`"))
        elif key not in used:
            stale.append((entry, "zizmor reports no such case; remove or correct the entry"))
    recorded = []
    for item in mapping.recorded:
        if item.set != set_name:
            continue
        got = [h for h in result_of(item.file).hits if h.rule in item.rules and h.state != "fixed"]
        recorded.append((item, bool(got), got))
    return Comparison(set_name, outcomes, stale, recorded, errors)


def render(comparison: Comparison) -> str:
    lines = [f"set {comparison.set}:"]
    counts = {s: sum(o.status == s for o in comparison.outcomes) for s in ("answered", "silent", "unexplained")}
    lines.append(f"  {len(comparison.outcomes)} cases of the mapped audits: {counts['answered']} answered by OBAAF, "
                 f"{counts['silent']} silent with a recorded reason, {counts['unexplained']} silent without one")
    for o in comparison.outcomes:
        c = o.case
        where = f"{c.file}#{c.job}" if c.job else f"{c.file} (file)"
        lines_of = ",".join(str(n) for n in c.lines)
        hits = " ".join(sorted({f"{h.rule}/{h.job or '-'}/{h.state}" + (f"@{h.step[0]}" if h.step else "")
                                for h in o.hits}))
        if o.status == "answered":
            detail = hits
        else:
            detail = ("no finding of " + ", ".join(MAPPING_RULES.get(c.audit, [])) + " on " + "; ".join(o.unmet)
                      + (f" (OBAAF found: {hits})" if hits else ""))
            if o.status == "silent":
                detail = o.reason + " [" + detail + "]"
        lines.append(f"  [{o.status}] {where} {c.audit} ({c.severity}, {c.confidence} confidence; line {lines_of}): "
                     f"{detail}")
    for entry, why in comparison.stale:
        lines.append(f"  [stale] silent entry {entry.file}#{entry.job} {entry.audit}: {why}")
    for item, ok, got in comparison.recorded:
        status = "answered" if ok else "unexplained"
        lines.append(f"  [{status}] {item.file} {item.tool} {item.result}: "
                     + (" ".join(sorted({f'{h.rule}/{h.job or "-"}' for h in got})) if ok
                        else "OBAAF reports none of " + ", ".join(item.rules)))
    for rel, errs in sorted(comparison.errors.items()):
        for err in errs:
            lines.append(f"  [obaaf could not read] {rel}: {err}")
    return "\n".join(lines)


MAPPING_RULES: dict = {}


def _roots(pairs: list[str] | None) -> dict:
    out = {}
    for pair in pairs or []:
        name, sep, value = pair.partition("=")
        if not sep or not name or not value:
            raise ParityError(f"expected SET=VALUE, got {pair!r}")
        out[name] = value
    return out


def base_of(mapping: Mapping, name: str, roots: dict) -> Path:
    if name in roots:
        return Path(roots[name]).resolve()
    fileset = mapping.sets[name]
    if fileset.repository:
        raise ParityError(f"set {name} is from {fileset.repository}; give --root {name}=DIR")
    return ROOT / fileset.root


