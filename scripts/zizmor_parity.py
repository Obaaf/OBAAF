#!/usr/bin/env python3
"""OBAAF's parity test against zizmor (flagship slice 2d.3b, decision F-19).

tests/parity/zizmor.yaml pairs zizmor audits with the OBAAF rules that answer them and lists the
workflow files compared. This script turns zizmor's JSON into cases (one per file, job and audit),
compares OBAAF's findings with them, and says which cases OBAAF is silent on without a recorded
reason.

    python scripts/zizmor_parity.py lock [--check | --print]
        write, check or print tests/parity/zizmor-requirements.txt: the pinned zizmor with the
        SHA-256 of every file PyPI publishes for it (needs PyPI)
    python scripts/zizmor_parity.py files SET [--root DIR]
        print the files of SET, relative to its root, one per line, for zizmor to read
    python scripts/zizmor_parity.py run --zizmor PROGRAM --out DIR [--root SET=DIR ...]
        run the pinned zizmor on every set, with the arguments zizmor.yaml gives, writing DIR/SET.json
    python scripts/zizmor_parity.py ci --zizmor SET=FILE ... [--root SET=DIR ...]
        CI: check that zizmor's output for the mapped audits is what zizmor-cases.json records,
        then compare OBAAF with it; prints CASES and the full comparison, exits 1 on any failure
    python scripts/zizmor_parity.py compare [--set SET ...] [--root SET=DIR ...]
        compare OBAAF with the recorded cases (no zizmor needed); a set whose files are not here
        is skipped and said so

Uses the standard library, PyYAML and OBAAF itself.
"""
from __future__ import annotations

import argparse
import fnmatch
import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARITY = ROOT / "tests" / "parity"
MAPPING = PARITY / "zizmor.yaml"
CASES = PARITY / "zizmor-cases.json"
LOCK = PARITY / "zizmor-requirements.txt"
FORMAT = "obaaf-zizmor-parity/v1"
CASES_FORMAT = "obaaf-zizmor-cases/v1"
SEVERITIES = ("informational", "low", "medium", "high")
CONFIDENCES = ("low", "medium", "high")
LOCK_HEADER = """\
# Generated by `python scripts/zizmor_parity.py lock` from the version in zizmor.yaml. Do not edit by
# hand. zizmor, by exact version and the SHA-256 of every file PyPI publishes for it, for CI's
# advisory job `zizmor-parity`. Install with:
#   pip install --require-hashes --only-binary=:all: --no-deps --requirement zizmor-requirements.txt
"""


class ParityError(Exception):
    """The mapping, a cases file or zizmor's output is not what this script reads."""


# ---------------------------------------------------------------------------------------------
# The mapping


@dataclass
class FileSet:
    name: str
    root: str
    include: list
    exclude: list = field(default_factory=list)
    repository: str = ""
    commit: str = ""

    def files(self, base: Path) -> list[str]:
        """The set's files under base, relative to it, in POSIX form and sorted."""
        if not base.is_dir():
            raise ParityError(f"set {self.name!r}: {base} is not a directory")
        out = []
        for path in sorted(base.rglob("*")):
            if not path.is_file() or path.is_symlink():
                continue
            rel = path.relative_to(base).as_posix()
            if any(_glob(rel, pattern) for pattern in self.include) and not any(
                    _glob(rel, pattern) for pattern in self.exclude):
                out.append(rel)
        return sorted(out)


def _glob(rel: str, pattern: str) -> bool:
    """fnmatch where `**/` also matches no folder, so `a/**/*.yml` takes `a/x.yml`."""
    if fnmatch.fnmatchcase(rel, pattern):
        return True
    return "**/" in pattern and fnmatch.fnmatchcase(rel, pattern.replace("**/", "", 1))


KINDS = ("narrower", "gap")


@dataclass
class Silent:
    set: str
    file: str
    job: str | None
    audit: str
    reason: str
    kind: str = "narrower"   # narrower: OBAAF's rule is narrower on purpose; gap: OBAAF should report
    issue: str = ""          # for a gap, the issue that tracks it (#N)


@dataclass
class Recorded:
    tool: str
    result: str
    set: str
    file: str
    rules: list


@dataclass
class Mapping:
    version: str
    arguments: list
    audits: dict
    sets: dict
    silent: list
    recorded: list


def _text(value, where: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ParityError(f"{where}: expected text, got {value!r}")
    return value


def _texts(value, where: str) -> list:
    if not isinstance(value, list) or not value:
        raise ParityError(f"{where}: expected a list of text")
    return [_text(v, f"{where}[{i}]") for i, v in enumerate(value)]


def _keys(entry, allowed: set, where: str) -> dict:
    if not isinstance(entry, dict):
        raise ParityError(f"{where}: expected a mapping")
    extra = set(entry) - allowed
    if extra:
        raise ParityError(f"{where}: unknown keys {sorted(extra)}")
    return entry


def load_mapping(path: Path = MAPPING) -> Mapping:
    import yaml

    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    data = _keys(data, {"format", "zizmor", "audits", "sets", "silent", "recorded"}, str(path))
    if data.get("format") != FORMAT:
        raise ParityError(f"{path}: format must be {FORMAT}")
    zizmor = _keys(data.get("zizmor"), {"version", "arguments"}, "zizmor")
    version = _text(zizmor.get("version"), "zizmor.version")
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ParityError(f"zizmor.version: expected an exact version, got {version!r}")
    arguments = _texts(zizmor.get("arguments"), "zizmor.arguments")
    audits_in = data.get("audits")
    if not isinstance(audits_in, dict) or not audits_in:
        raise ParityError("audits: expected a mapping of zizmor audits to OBAAF rules")
    audits = {}
    for audit, rules in audits_in.items():
        rules = _texts(rules, f"audits.{audit}")
        if not all(re.fullmatch(r"OBAAF-GHA-\d{3}", r) for r in rules):
            raise ParityError(f"audits.{audit}: expected OBAAF-GHA-NNN rule ids")
        audits[_text(audit, "audits")] = rules
    sets = {}
    for name, entry in (data.get("sets") or {}).items():
        entry = _keys(entry, {"about", "root", "include", "exclude", "repository", "commit"}, f"sets.{name}")
        _text(entry.get("about"), f"sets.{name}.about")
        commit = entry.get("commit", "")
        if entry.get("repository") and not re.fullmatch(r"[0-9a-f]{40}", str(commit)):
            raise ParityError(f"sets.{name}.commit: a set from another repository needs a full commit")
        sets[name] = FileSet(name, _text(entry.get("root"), f"sets.{name}.root"),
                             _texts(entry.get("include"), f"sets.{name}.include"),
                             list(entry.get("exclude") or []), entry.get("repository", ""), commit)
    if not sets:
        raise ParityError("sets: expected at least one set")
    silent = []
    seen = set()
    for i, entry in enumerate(data.get("silent") or []):
        where = f"silent[{i}]"
        entry = _keys(entry, {"set", "file", "job", "audit", "kind", "issue", "reason"}, where)
        item = Silent(_text(entry.get("set"), f"{where}.set"), _text(entry.get("file"), f"{where}.file"),
                      entry.get("job"), _text(entry.get("audit"), f"{where}.audit"),
                      _text(entry.get("reason"), f"{where}.reason"), _text(entry.get("kind"), f"{where}.kind"),
                      str(entry.get("issue") or ""))
        if item.kind not in KINDS:
            raise ParityError(f"{where}.kind: one of {', '.join(KINDS)}")
        if (item.kind == "gap") != bool(re.fullmatch(r"#\d+", item.issue)):
            raise ParityError(f"{where}: a gap names its issue as #N, and only a gap names one")
        if item.set not in sets:
            raise ParityError(f"{where}: no set {item.set!r}")
        if item.audit not in audits:
            raise ParityError(f"{where}: {item.audit!r} is not a mapped audit")
        if item.job is not None:
            _text(item.job, f"{where}.job")
        if len(item.reason.split()) < 6:
            raise ParityError(f"{where}.reason: say why OBAAF is silent, in a sentence")
        key = (item.set, item.file, item.job, item.audit)
        if key in seen:
            raise ParityError(f"{where}: names the same case as an earlier entry")
        seen.add(key)
        silent.append(item)
    recorded = []
    for i, entry in enumerate(data.get("recorded") or []):
        where = f"recorded[{i}]"
        entry = _keys(entry, {"tool", "result", "set", "file", "rules"}, where)
        item = Recorded(_text(entry.get("tool"), f"{where}.tool"), _text(entry.get("result"), f"{where}.result"),
                        _text(entry.get("set"), f"{where}.set"), _text(entry.get("file"), f"{where}.file"),
                        _texts(entry.get("rules"), f"{where}.rules"))
        if item.set not in sets:
            raise ParityError(f"{where}: no set {item.set!r}")
        recorded.append(item)
    return Mapping(version, arguments, audits, sets, silent, recorded)


# ---------------------------------------------------------------------------------------------
# zizmor's output, as cases


@dataclass(frozen=True)
class Case:
    """What zizmor reported for one audit on one job of one file (job None: the file as a whole)."""

    file: str
    job: str | None
    audit: str
    severity: str
    confidence: str
    lines: tuple

    def key(self) -> tuple:
        return (self.file, self.job, self.audit)

    def as_dict(self) -> dict:
        return {"file": self.file, "job": self.job, "audit": self.audit, "severity": self.severity,
                "confidence": self.confidence, "lines": list(self.lines)}


def _route(location: dict) -> list:
    """The keys and indices of a zizmor location's route, which yamlpath writes as
    {"route": [{"Key": "jobs"}, {"Index": 0}, ...]}."""
    route = location.get("symbolic", {}).get("route")
    if isinstance(route, dict):
        route = route.get("route")
    if not isinstance(route, list):
        raise ParityError(f"zizmor location without a route list: {location!r:.200}")
    out = []
    for part in route:
        if isinstance(part, dict) and len(part) == 1:
            kind, value = next(iter(part.items()))
            if kind == "Key" and isinstance(value, str):
                out.append(value)
                continue
            if kind == "Index" and isinstance(value, int):
                out.append(value)
                continue
        raise ParityError(f"zizmor route part not read: {part!r:.200}")
    return out


def _file(location: dict) -> str:
    key = location.get("symbolic", {}).get("key")
    if not isinstance(key, dict) or "Local" not in key:
        raise ParityError(f"zizmor location that is not a local file: {key!r:.200}")
    path = key["Local"].get("verbatim_path") if isinstance(key["Local"], dict) else None
    if not isinstance(path, str) or not path:
        raise ParityError(f"zizmor location without a path: {key!r:.200}")
    path = path.replace("\\", "/")
    while path.startswith("./"):
        path = path[2:]
    return path


def _primary(locations: list) -> dict:
    """The location zizmor marks primary; failing that, the first it does not hide."""
    if not isinstance(locations, list) or not locations:
        raise ParityError("zizmor finding without locations")
    for kind in ("Primary", "Related"):
        for location in locations:
            if isinstance(location, dict) and location.get("symbolic", {}).get("kind") == kind:
                return location
    raise ParityError("zizmor finding with only hidden locations")


def cases_from_zizmor(findings, audits) -> list[Case]:
    """zizmor's json-v1 output (a list of findings) as cases of the given audits, one per file, job
    and audit, with the highest severity and confidence and every line reported."""
    if not isinstance(findings, list):
        raise ParityError("zizmor's json-v1 output is a list of findings")
    grouped: dict = {}
    for finding in findings:
        if not isinstance(finding, dict) or not isinstance(finding.get("ident"), str):
            raise ParityError(f"not a zizmor finding: {finding!r:.200}")
        if finding["ident"] not in audits or finding.get("ignored"):
            continue
        det = finding.get("determinations") or {}
        severity = str(det.get("severity", "")).lower()
        confidence = str(det.get("confidence", "")).lower()
        if severity not in SEVERITIES or confidence not in CONFIDENCES:
            raise ParityError(f"zizmor determinations not read: {det!r}")
        location = _primary(finding.get("locations"))
        route = _route(location)
        job = route[1] if len(route) > 1 and route[0] == "jobs" and isinstance(route[1], str) else None
        row = location.get("concrete", {}).get("location", {}).get("start_point", {}).get("row")
        line = row + 1 if isinstance(row, int) else 0
        key = (_file(location), job, finding["ident"])
        sev, conf, lines = grouped.get(key, ("informational", "low", set()))
        grouped[key] = (max(sev, severity, key=SEVERITIES.index), max(conf, confidence, key=CONFIDENCES.index),
                        lines | {line})
    return sorted((Case(f, j, a, s, c, tuple(sorted(ls))) for (f, j, a), (s, c, ls) in grouped.items()),
                  key=lambda c: (c.file, c.job or "", c.audit))


def load_cases(path: Path = CASES) -> dict:
    """The recorded cases: {"zizmor": version, "sets": {set: [Case, ...]}}."""
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or data.get("format") != CASES_FORMAT:
        raise ParityError(f"{path}: format must be {CASES_FORMAT}")
    sets = {}
    for name, items in (data.get("sets") or {}).items():
        out = []
        for item in items:
            if not isinstance(item, dict) or set(item) != {"file", "job", "audit", "severity", "confidence", "lines"}:
                raise ParityError(f"{path}: set {name}: not a case: {item!r:.200}")
            out.append(Case(item["file"], item["job"], item["audit"], item["severity"], item["confidence"],
                            tuple(item["lines"])))
        sets[name] = out
    return {"zizmor": data.get("zizmor"), "sets": sets}


def dump_cases(version: str, sets: dict) -> str:
    return json.dumps({"format": CASES_FORMAT, "zizmor": version,
                       "sets": {name: [c.as_dict() for c in cases] for name, cases in sorted(sets.items())}},
                      indent=1, sort_keys=False) + "\n"


# ---------------------------------------------------------------------------------------------
# OBAAF's findings, and the comparison


@dataclass(frozen=True)
class Hit:
    rule: str
    job: str | None
    state: str


def obaaf_findings(path: Path) -> tuple[list[Hit], list[str]]:
    """What `obaaf check FILE` (no configuration, GitHub Actions) finds on one workflow file."""
    from obaaf import checker

    config = checker.Config.load(path.parent, None)
    result = checker.check(path, config=config, platform="github")
    return [Hit(f.rule, f.job, f.state) for f in result.findings], list(result.errors)


@dataclass
class Outcome:
    case: Case
    status: str        # answered, silent (recorded), unexplained
    hits: list = field(default_factory=list)
    reason: str = ""


@dataclass
class Comparison:
    set: str
    outcomes: list
    stale: list        # silent entries that name no case, or a case OBAAF answers: (entry, why)
    recorded: list     # (Recorded, ok: bool, hits)
    errors: dict       # file -> OBAAF's errors on it

    @property
    def failures(self) -> int:
        return (sum(o.status == "unexplained" for o in self.outcomes) + len(self.stale)
                + sum(not ok for _, ok, _ in self.recorded))


def compare(mapping: Mapping, set_name: str, cases: list[Case], base: Path, findings=obaaf_findings) -> Comparison:
    fileset = mapping.sets[set_name]
    files = set(fileset.files(base))
    by_file: dict = {}
    errors: dict = {}

    def hits_on(rel: str) -> list[Hit]:
        if rel not in by_file:
            if rel not in files:
                raise ParityError(f"set {set_name}: zizmor reported {rel}, which is not among the set's files")
            hits, errs = findings(base / rel)
            by_file[rel] = hits
            if errs:
                errors[rel] = errs
        return by_file[rel]

    silent = {(s.file, s.job, s.audit): s for s in mapping.silent if s.set == set_name}
    used: set = set()
    outcomes = []
    for case in cases:
        if case.audit not in mapping.audits:
            continue
        rules = mapping.audits[case.audit]
        answer = [h for h in hits_on(case.file) if h.rule in rules and h.state != "fixed"
                  and (case.job is None or h.job is None or h.job == case.job)]
        entry = silent.get(case.key())
        if answer:
            outcomes.append(Outcome(case, "answered", answer))
        elif entry is not None:
            used.add(case.key())
            label = f"{entry.kind}: " if entry.kind == "narrower" else f"gap ({entry.issue}): "
            outcomes.append(Outcome(case, "silent", reason=label + entry.reason))
        else:
            outcomes.append(Outcome(case, "unexplained"))
    answered = {o.case.key() for o in outcomes if o.status == "answered"}
    stale = []
    for key, entry in silent.items():
        if key in answered:
            stale.append((entry, "OBAAF now answers this case; remove the entry"))
        elif key not in used:
            stale.append((entry, "zizmor reports no such case; remove or correct the entry"))
    recorded = []
    for item in mapping.recorded:
        if item.set != set_name:
            continue
        got = [h for h in hits_on(item.file) if h.rule in item.rules]
        recorded.append((item, bool(got), got))
    return Comparison(set_name, outcomes, stale, recorded, errors)


def render(comparison: Comparison) -> str:
    lines = [f"set {comparison.set}:"]
    counts = {s: sum(o.status == s for o in comparison.outcomes) for s in ("answered", "silent", "unexplained")}
    lines.append(f"  {len(comparison.outcomes)} cases of the mapped audits: {counts['answered']} answered by OBAAF, "
                 f"{counts['silent']} silent with a recorded reason, {counts['unexplained']} silent without one")
    for o in comparison.outcomes:
        c = o.case
        where = f"{c.file}#{c.job}" if c.job else f"{c.file} (file)"
        lines_of = ",".join(str(n) for n in c.lines)
        detail = (" ".join(sorted({f"{h.rule}/{h.job or '-'}/{h.state}" for h in o.hits})) if o.status == "answered"
                  else o.reason if o.status == "silent" else "OBAAF reports none of " + ", ".join(
                      sorted(set(MAPPING_RULES.get(c.audit, [])))))
        lines.append(f"  [{o.status}] {where} {c.audit} ({c.severity}, {c.confidence} confidence; line {lines_of}): "
                     f"{detail}")
    for entry, why in comparison.stale:
        lines.append(f"  [stale] silent entry {entry.file}#{entry.job} {entry.audit}: {why}")
    for item, ok, got in comparison.recorded:
        status = "answered" if ok else "unexplained"
        lines.append(f"  [{status}] {item.file} {item.tool} {item.result}: "
                     + (" ".join(sorted({f'{h.rule}/{h.job or "-"}' for h in got})) if ok
                        else "OBAAF reports none of " + ", ".join(item.rules)))
    for rel, errs in sorted(comparison.errors.items()):
        for err in errs:
            lines.append(f"  [obaaf error] {rel}: {err}")
    return "\n".join(lines)


MAPPING_RULES: dict = {}


def _roots(pairs: list[str] | None) -> dict:
    out = {}
    for pair in pairs or []:
        name, sep, value = pair.partition("=")
        if not sep or not name or not value:
            raise ParityError(f"expected SET=VALUE, got {pair!r}")
        out[name] = value
    return out


def base_of(mapping: Mapping, name: str, roots: dict) -> Path:
    if name in roots:
        return Path(roots[name]).resolve()
    fileset = mapping.sets[name]
    if fileset.repository:
        raise ParityError(f"set {name} is from {fileset.repository}; give --root {name}=DIR")
    return ROOT / fileset.root


