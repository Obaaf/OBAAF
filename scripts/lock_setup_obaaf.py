#!/usr/bin/env python3
"""Generate actions/setup-obaaf/requirements.txt, OBAAF's hash-pinned install list (D-011).

Every dependency pinned in actions/setup-obaaf/constraints.txt is written with the
SHA-256 of every file PyPI publishes for that exact version, so `pip install
--require-hashes` accepts only those files on any operating system or Python version.

    python scripts/lock_setup_obaaf.py           write requirements.txt from constraints.txt
    python scripts/lock_setup_obaaf.py --check   fail if requirements.txt differs from PyPI

Edit constraints.txt, never requirements.txt. Uses only the standard library.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONSTRAINTS = ROOT / "actions" / "setup-obaaf" / "constraints.txt"
LOCK = ROOT / "actions" / "setup-obaaf" / "requirements.txt"
PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;#]+)\s*$")
SHA256 = re.compile(r"^[0-9a-f]{64}$")
HEADER = """\
# Generated by scripts/lock_setup_obaaf.py from constraints.txt. Do not edit by hand.
# Every dependency of OBAAF's pipeline install, by exact version and the SHA-256 of
# every file PyPI publishes for it. Install with:
#   pip install --require-hashes --only-binary=:all: --requirement requirements.txt
# (DECISIONS.md, D-011)
"""


def pins(text: str) -> list[tuple[str, str]]:
    """The name==version lines of a constraints file, in order."""
    out = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = PIN.match(line)
        if not match:
            raise ValueError(f"constraints.txt: expected name==version, got {raw!r}")
        out.append((match.group(1), match.group(2)))
    return out


def pypi_hashes(name: str, version: str, fetch=None) -> list[str]:
    """SHA-256 digests of every file PyPI publishes for name==version."""
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    if fetch is None:
        def fetch(u):
            with urllib.request.urlopen(u, timeout=30) as response:  # noqa: S310 (fixed https URL)
                return json.load(response)
    data = fetch(url)
    digests = sorted({f["digests"]["sha256"] for f in data.get("urls", [])})
    if not digests or not all(SHA256.match(d) for d in digests):
        raise ValueError(f"PyPI returned no usable SHA-256 digests for {name}=={version}")
    return digests


def render(entries: list[tuple[str, str, list[str]]]) -> str:
    lines = [HEADER]
    for name, version, digests in entries:
        lines.append(f"{name}=={version} \\")
        lines.extend(f"    --hash=sha256:{d} \\" for d in digests[:-1])
        lines.append(f"    --hash=sha256:{digests[-1]}")
    return "\n".join(lines) + "\n"


def build(fetch=None) -> str:
    return render([(n, v, pypi_hashes(n, v, fetch)) for n, v in pins(CONSTRAINTS.read_text(encoding="utf-8"))])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if requirements.txt is missing or out of date")
    args = parser.parse_args(argv)
    text = build()
    if args.check:
        current = LOCK.read_text(encoding="utf-8") if LOCK.is_file() else ""
        if current != text:
            print(f"{LOCK.relative_to(ROOT)} does not match constraints.txt and PyPI. "
                  "Run: python scripts/lock_setup_obaaf.py, or download the setup-obaaf-requirements "
                  "artifact from this CI run and commit it to actions/setup-obaaf/.", file=sys.stderr)
            return 1
        print(f"{LOCK.relative_to(ROOT)} matches constraints.txt and PyPI.")
        return 0
    LOCK.write_text(text, encoding="utf-8")
    print(f"wrote {LOCK.relative_to(ROOT)} ({len(pins(CONSTRAINTS.read_text(encoding='utf-8')))} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
