"""Generate the human-readable specifications and the offline form from the data files.

`obaaf docs build` writes:

    spec/profile.md            the build-integrity profile (FR1)
    spec/agent-controls.md     the agent controls R1–R8
    spec/self-assessment.md    the printable self-assessment checklist
    spec/checker-rules.md      the checker's rules and its test set (FR12)
    assessment/obaaf-self-assessment.html   the offline form (FR2)

`obaaf docs build --check` fails when any of them is out of date, so the data
files stay the single source of truth (NFR7).
"""

from __future__ import annotations

import html
import json
import re
from pathlib import Path

from obaaf import __version__
from obaaf.catalog import Catalog, load

GENERATED = "<!-- Generated by `obaaf docs build` from src/obaaf/data/. Do not edit by hand. -->"
DRAFT_NOTE = ("*Version 0.1, in active adoption with pilot teams. It may change in version 0.2 based on pilot "
              "feedback; open design decisions are tracked in [DECISIONS.md](../DECISIONS.md).*")


def _clean(text: str) -> str:
    return " ".join(str(text).split())


def anchor(heading: str) -> str:
    """The anchor GitHub generates for a Markdown heading."""
    slug = re.sub(r"[^\w\- ]", "", heading.strip().lower())
    return slug.replace(" ", "-")


def _items_for(catalog: Catalog, gid: str) -> str:
    items = [i["id"] for i in catalog.items_for_requirement(gid)]
    return ", ".join(items) if items else "-"


def _ssdf_id(catalog: Catalog, ref: str) -> str:
    """An SSDF reference as the paper writes it: practices from the draft of version 1.2 say so."""
    practice = catalog.frameworks["ssdf"]["practices"].get(ref)
    return f"{ref} (draft 1.2)" if practice and practice.get("version") == "1.2-ipd" else ref


def _ssdf(catalog: Catalog, refs: list[str]) -> str:
    """Practice titles as NIST writes them; task text is summarized, and says so."""
    tasks = catalog.frameworks["ssdf"].get("tasks", {})
    return "; ".join(f"{_ssdf_id(catalog, r)}: {catalog.ssdf_title(r)}" + (" (task, summarized)" if r in tasks else "")
                     for r in refs) if refs else "-"


def _addresses(req: dict) -> str:
    addr = req["addresses"]
    if addr.get("as_written"):
        return addr["as_written"]
    return "; ".join(x for x in (", ".join(addr["attack_paths"]), ", ".join(addr["properties"])) if x) or "-"


# ----------------------------------------------------------------------- profile
def profile_md(catalog: Catalog | None = None) -> str:
    c = catalog or load()
    p = c.profile
    out = ["# Build-integrity profile", "", GENERATED, "", DRAFT_NOTE, "",
           f"Version {p['version']} ({p['status']}). Source: {p['source']} (*Securing the Game Build*). The profile "
           "tailors NIST's Secure Software Development Framework (SSDF) and SLSA to software build and release "
           "pipelines: 28 requirements in nine control families, each guarding one step on the path from commit to "
           "user. Developed with independent game studios and grounded in their pipelines, the control families "
           "apply to any team that builds and ships software; a few requirements name game-specific cases and are "
           "marked where they do not apply. Each requirement has a test that passes or fails, the evidence to "
           "inspect, and its mappings.", "",
           "The requirement statements, the attack paths and properties each addresses, and the SSDF and SLSA "
           "mappings are quoted from the paper's Table 4. The titles, rationales, tests and evidence are new drafts "
           "written for this repository; they await the author's review ([DECISIONS.md](../DECISIONS.md), D-004).",
           ""]
    out += ["## Isolation tiers", "", "| Tier | Meaning |", "| --- | --- |"]
    out += [f"| {k} | {_clean(v)} |" for k, v in p["isolation_tiers"].items()]
    out += ["", "Isolation tiers A and B are separate from the four self-assessment tiers.", ""]
    out += ["## Attack paths and game properties", "", "| ID | Attack path |", "| --- | --- |"]
    out += [f"| {k} | {v} |" for k, v in p["attack_paths"].items()]
    out += ["", "| ID | Property of game development |", "| --- | --- |"]
    out += [f"| {k} | {v} |" for k, v in p["properties"].items()]
    out += ["", "## Summary", "", "| ID | Requirement | Addresses | SSDF | SLSA or other | Assessment items |",
            "| --- | --- | --- | --- | --- | --- |"]
    for fam in p["families"]:
        out.append(f"| **{fam['id']}** | **{fam['title']}** | | | | |")
        for r in fam["requirements"]:
            ssdf_ids = ", ".join(_ssdf_id(c, x) for x in r["ssdf"]) or "-"
            out.append(f"| [{r['id']}](#{anchor(r['id'] + ' ' + r['title'])}) | {r['title']} | {_addresses(r)} | "
                       f"{ssdf_ids} | {r['slsa_or_other']} | {_items_for(c, r['id'])} |")
    out.append("")
    for fam in p["families"]:
        out += [f"## {fam['id']} {fam['title']}", ""]
        for r in fam["requirements"]:
            gid = r["id"]
            out += [f"### {gid} {r['title']}", "", f"**Requirement.** {_clean(r['statement'])}.", "",
                    f"**Addresses.** {_addresses(r)}", "",
                    f"**Why.** {_clean(r['rationale'])}", "", f"**Test.** {_clean(r['test'])}", "",
                    f"**Evidence.** {_clean(r['evidence'])}", ""]
            maps = [f"SSDF: {_ssdf(c, r['ssdf'])}"]
            if r["slsa_or_other"] not in ("-", ""):
                maps.append(f"SLSA or other (Table 4): {r['slsa_or_other']}")
            if r.get("slsa"):
                maps.append("SLSA v1.2 requirements: " +
                            "; ".join(c.frameworks["slsa"]["requirements"][s]["title"] for s in r["slsa"]))
            if r.get("agent_controls"):
                maps.append("Agent controls: " + ", ".join(r["agent_controls"]))
            maps.append(f"Assessment items: {_items_for(c, gid)}")
            if r.get("checks"):
                maps.append("Checker rules: " + ", ".join(f"`{x}`" for x in r["checks"]))
            if r.get("tools"):
                maps.append("Tools: " + ", ".join(f"`{x}`" for x in r["tools"]))
            out += ["**Maps to.** " + " · ".join(maps), ""]
    return "\n".join(out).rstrip() + "\n"


# ---------------------------------------------------------------- agent controls
def agent_controls_md(catalog: Catalog | None = None) -> str:
    c = catalog or load()
    a = c.controls
    out = ["# Agent controls", "", GENERATED, "", DRAFT_NOTE, "",
           f"Version {a['version']} ({a['status']}). Source: {a['source']} (*Untrusted Text, Trusted Tokens*). "
           "These controls let a team connect AI agents to its build pipeline without lending them "
           "the pipeline's authority. They are not specific to games.", "",
           f"## The principle: {a['principle']['name'].lower()}", "", _clean(a["principle"]["statement"]), "",
           "```latex", a["principle"]["formula"], "```", "",
           "Here *A*(α) is every capability reachable from the agent invocation α, req(*c*) is the lowest trust "
           "level allowed to cause capability *c*, and *I*(α) is the level of the least-trusted principal able to "
           "influence anything α reads.", "",
           "## Trust levels", "", "| Level | Typical capabilities at this level |", "| --- | --- |"]
    out += [f"| {t['id']} | {t['typical_capabilities']} |" for t in a["trust_levels"]]
    out += ["", "The levels form a chain: Public ⊑ Contributor ⊑ Maintainer ⊑ Release.", "",
            "## Lanes", "", "Three lanes and an attestation step (Paper 1, section 7.1), each a separate job with its own "
            "identity.", "", "| Lane or step | Runs at | What it does |", "| --- | --- | --- |"]
    out += [f"| {l.get('name') or l['id'].capitalize()} | {l['level']} | {_clean(l['summary'])} |" for l in a["lanes"]]
    out += ["", "The [GitHub Actions templates](../templates/github-actions/README.md) implement these lanes, with two "
            "gaps in version 0.1: the agent's egress is declared but enforced only with an egress monitor or a "
            "network policy, and the inference proxy is specified but not built yet "
            "([inference proxy](../docs/inference-proxy.md)).", "",
            "## Requirements", "", "| ID | Requirement | Root causes | SSDF | SLSA v1.2 | NIST NCCoE topic |",
            "| --- | --- | --- | --- | --- | --- |"]
    for r in a["requirements"]:
        out.append(f"| [{r['id']}](#{anchor(r['id'] + ' ' + r['title'])}) | "
                   f"{r['name']} | {', '.join(r['root_causes'])} | {', '.join(r['ssdf']) or 'None'} | {r['slsa']} | "
                   f"{r['nccoe']} |")
    out.append("")
    for r in a["requirements"]:
        impl = r.get("obaaf", {})
        parts = []
        for key, label in (("tools", "Tools"), ("templates", "Templates"), ("schemas", "Schemas"),
                           ("docs", "Docs"), ("checks", "Checker rules")):
            if impl.get(key):
                parts.append(f"{label}: " + ", ".join(f"`{x}`" for x in impl[key]))
        out += [f"### {r['id']} {r['title']}", "", f"**Requirement.** {_clean(r['statement'])}", "",
                f"**Why.** {_clean(r['rationale'])}", "",
                f"**Root causes.** {', '.join(r['root_causes'])}. **Assumption secured** (Paper 1, Table 2): "
                f"{r['assumption']}. **Illustrative cases.** {', '.join(r['cases'])}.", "",
                f"**On GitHub Actions.** Native: {r['github_native']}. Gap and compensating control: "
                f"{r['github_gap']}.", "",
                f"**New relative to existing standards.** {r['new']}.", ""]
        if parts:
            out += ["**In this repository.** " + " · ".join(parts), ""]
    out += ["## The agent-run record", "",
            "Each agent run produces a signed in-toto attestation. Fields the agent could influence are kept apart "
            "and marked untrusted. See [the attestation formats](../docs/attestations.md).", "",
            "| Field | Content | Produced by | Trusted |", "| --- | --- | --- | --- |"]
    out += [f"| {f['field']} | {f['content']} | {f['produced_by']} | {'Yes' if f['trusted'] else 'No (self-reported)'} |"
            for f in a["attestation_fields"]]
    out += ["", "*How version 0.1 differs from Paper 1, Table 3.* " + _clean(a["attestation_v01_note"])]
    out += ["", "## Documented incidents", "",
            "Under the assumptions of Paper 1, section 5.3, the requirements would have prevented (P) or contained "
            "(C) the harmful outcome in each case.", "",
            "| Case | Disclosed | Status | Root causes | Prevented by | Contained by |",
            "| --- | --- | --- | --- | --- | --- |"]
    for case in c.compromises["agent_cases"]:
        prevented = ", ".join(case["prevented_by"]) or "-"
        if case.get("prevented_condition"):
            prevented += f" ({case['prevented_condition']})"
        out.append(f"| {case['name']} | {case['disclosed']} | {case['status']} | {', '.join(case['root_causes'])} | "
                   f"{prevented} | {', '.join(case['contained_by']) or '-'} |")
    return "\n".join(out).rstrip() + "\n"


# ---------------------------------------------------------------- assessment
def self_assessment_md(catalog: Catalog | None = None) -> str:
    c = catalog or load()
    s = c.assessment
    effort = s["effort"]
    out = ["# Self-assessment checklist", "", GENERATED, "", DRAFT_NOTE, "",
           f"Version {s['version']} ({s['status']}). Source: {s['source']} (*Securing the Game Build*). For a software "
           "team without security staff: 34 yes-or-no questions in four tiers. Answer each from the evidence named "
           "beside it, which a second person can check. Effort is an initial estimate (hours, days or weeks) that "
           "the pilot will test.", "",
           "**How scoring works.** You reach a tier when every item at that tier and below is answered yes. An item "
           "may be marked not applicable (N/A) only when its condition is absent, as noted beside it; N/A counts as "
           "yes. A tier describes controls in place, not a guarantee of security.", "",
           "Fill it in on paper, in the [offline form](../assessment/obaaf-self-assessment.html), or as a file "
           "scored with `obaaf assess score`. Your answers never leave your machine.", ""]
    for tier_id in sorted(c.tiers):
        tier = c.tiers[tier_id]
        out += [f"## Tier {tier_id}: {tier['name']}", "", tier["summary"], "",
                "| ID | Question | Evidence a second person can check | Effort | Profile | Answer |",
                "| --- | --- | --- | --- | --- | --- |"]
        for iid, item in c.items.items():
            if item["tier"] != tier_id:
                continue
            q = item["question"] + (f" *N/A only if: {item['na_when']}*" if item.get("na_when") else "")
            boxes = "☐ Yes ☐ No" + (" ☐ N/A" if item.get("na_when") else "")
            profile = ", ".join(item["profile"]) + (f", Tier {item['isolation_tier']}" if item.get("isolation_tier")
                                                     else "")
            out.append(f"| {iid} | {q} | {item['evidence']} | {effort[item['effort']]['label']} | "
                       f"{profile} | {boxes} |")
        out.append("")
    out += ["## How to fix a 'no'", "", "| ID | Item | Where to start |", "| --- | --- | --- |"]
    for iid, item in c.items.items():
        links = ", ".join(f"[{_label(l)}](../{l})" for l in item["fix"])
        out.append(f"| {iid} | {item['short']} | {links} |")
    out += ["", "## Traceability", "", "Every SLSA Build-track requirement group and every Source-track level maps to "
            "at least one item (Paper 2, Table 8).", "", "| Framework requirement | Items |", "| --- | --- |"]
    out += [f"| {row['framework']} {row['requirement']} | {row.get('as_written') or ', '.join(row['items'])} |"
            for row in s["traceability"]]
    return "\n".join(out).rstrip() + "\n"


def _label(link: str) -> str:
    """A short readable name for a fix link."""
    path, _, frag = link.partition("#")
    name = Path(path).name
    if frag.startswith("item-"):
        return "guide for item " + frag[len("item-"):].replace("-", ".", 1)
    if name.endswith((".yml", ".yaml")) and "workflows" in path:
        return f"{name} template"
    if name == "CODEOWNERS.example":
        return "CODEOWNERS example"
    if name == "github-settings.md":
        return "GitHub settings"
    return Path(name).stem.replace("-", " ")


# ---------------------------------------------------------------- checker rules
def checker_rules_md(catalog: Catalog | None = None, test_set: list[dict] | None = None) -> str:
    c = catalog or load()
    out = ["# Pipeline checker rules", "", GENERATED, "", DRAFT_NOTE, "",
           "`obaaf check` reads GitHub Actions workflow files, CODEOWNERS and agent instruction files, and reports "
           "settings that open a documented attack path. Each finding names the profile requirement and agent "
           "control it threatens, and the fix. It runs locally and sends nothing over the network.", "",
           "Each rule is either an **authority** finding (who or what can change, build, release or sign, and the "
           "controls that bound an agent's authority) or a **hygiene** finding (pinning and hardening). The checker "
           "summary and the SARIF output report the two separately, so authority findings are not buried under "
           "hygiene ones. Declaring agent entry points, lane overrides and expiring ignores is described in "
           "[checker configuration](../docs/checker-configuration.md).", "",
           "| Rule | Severity | Category | What it finds | Requirements |", "| --- | --- | --- | --- | --- |"]
    for rid, rule in c.rules.items():
        refs = ", ".join(list(rule.get("requirements", [])) + list(rule.get("agent_controls", []))) or "-"
        out.append(f"| [{rid}](#{anchor(rid)}) | {rule['severity']} | {rule.get('category', 'authority')} | "
                   f"{rule['title']} | {refs} |")
    out.append("")
    for rid, rule in c.rules.items():
        refs = ", ".join(list(rule.get("requirements", [])) + list(rule.get("agent_controls", []))) or "-"
        out += [f"## {rid}", "", f"**{rule['title']}** ({rule['severity']}). Requirements: {refs}. "
                f"Supports: {', '.join(rule.get('supports', [])) or '-'}.", "", _clean(rule["description"]), "",
                f"**Fix.** {_clean(rule['fix'])}", ""]
        if rule.get("remediation") == "architecture":
            out += ["**Remediation.** Fixing this means adopting the agent and effect lanes, not a one-line change. "
                    "See the [lane templates](../templates/github-actions/README.md).", ""]
    if test_set:
        out += ["## Test set", "",
                "Each workflow below models a documented attack pattern. The checker must report every expected rule "
                "for it (FR12); `tests/test_fr12_checker.py` enforces this.", "",
                "| Test workflow | Models | Expected rules |", "| --- | --- | --- |"]
        for case in test_set:
            out.append(f"| `{case['file']}` | {case['models']} | {', '.join(case['expect'])} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def read_test_set(fixtures_dir: Path) -> list[dict]:
    cases = []
    for path in sorted(fixtures_dir.glob("*.yml")):
        text = path.read_text(encoding="utf-8")
        expect = re.search(r"^# obaaf-expect:\s*(.+)$", text, re.M)
        models = re.search(r"^# obaaf-models:\s*(.+)$", text, re.M)
        if expect:
            cases.append({"file": f"tests/fixtures/workflows/risky/{path.name}",
                          "expect": expect.group(1).split(), "models": models.group(1).strip() if models else ""})
    return cases


# ---------------------------------------------------------------- offline form
FORM_TEMPLATE = Path(__file__).with_name("form_template.html")


def form_data(catalog: Catalog | None = None, link_base: str = "../") -> dict:
    c = catalog or load()
    items = []
    for iid, item in c.items.items():
        cases = c.item_cases(iid)
        items.append({
            "id": iid, "tier": item["tier"], "short": item["short"], "question": item["question"],
            "evidence": item["evidence"], "effort": item["effort"],
            "profile": item["profile"] + ([f"Tier {item['isolation_tier']}"] if item.get("isolation_tier") else []),
            "naWhen": item.get("na_when") or "",
            "fix": [{"href": link_base + l, "label": _label(l)} for l in item["fix"]],
            "prevents": [f"{x['name']} ({x['reported']})" for x in cases["prevent"]],
            "limits": [f"{x['name']} ({x['reported']})" for x in cases["limit"]],
        })
    return {
        "format": "obaaf-assessment/v0.1",
        "version": c.assessment["version"],
        "tool": __version__,
        "tiers": [{"id": t["id"], "name": t["name"], "summary": t["summary"]} for t in c.assessment["tiers"]],
        "effort": {k: v for k, v in c.assessment["effort"].items()},
        "items": items,
    }


def form_html(catalog: Catalog | None = None, link_base: str = "../") -> str:
    data = json.dumps(form_data(catalog, link_base), ensure_ascii=False, separators=(",", ":"))
    data = data.replace("</", "<\\/")  # keep the JSON from closing the script element
    template = FORM_TEMPLATE.read_text(encoding="utf-8")
    return template.replace("/*OBAAF_DATA*/{}", data).replace("{{VERSION}}", html.escape(__version__))


# ---------------------------------------------------------------- build
def outputs(root: Path, catalog: Catalog | None = None) -> dict[Path, str]:
    c = catalog or load()
    test_set = read_test_set(root / "tests" / "fixtures" / "workflows" / "risky")
    return {
        root / "spec" / "profile.md": profile_md(c),
        root / "spec" / "agent-controls.md": agent_controls_md(c),
        root / "spec" / "self-assessment.md": self_assessment_md(c),
        root / "spec" / "checker-rules.md": checker_rules_md(c, test_set),
        root / "assessment" / "obaaf-self-assessment.html": form_html(c),
    }


def build(root: Path, check_only: bool = False) -> list[Path]:
    """Write the generated files; with check_only, return the ones that are out of date."""
    stale = []
    for path, content in outputs(root).items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != content:
            stale.append(path)
            if not check_only:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    return stale
